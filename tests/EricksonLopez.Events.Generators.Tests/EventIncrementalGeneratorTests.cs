        runResult.GeneratedTrees.Should().HaveCount(2);

        var extensionsTree = runResult.GeneratedTrees.FirstOrDefault(t => t.FilePath.Contains("GeneratedEventServiceCollectionExtensions"));
        extensionsTree.Should().NotBeNull();

