    [Fact]
    public void Generator_ShouldDiscoverEventsAndEmitGeneratedRegistry_WithExactSourceAndRuntimeExecution()
    {
        var sourceCode = @"
namespace TestApp
{
    public static class EventConstants
    {
        public const string OrderPlacedName = ""test.order-placed"";
    }

    [EventName(EventConstants.OrderPlacedName)]
    [EventVersion(2)]
    [EventSource(""test-service"")]
    public sealed record TestOrderPlaced(EventId Id, DateTimeOffset OccurredAt) : IDomainEvent;

    public sealed record PlainDiscoveredEvent(EventId Id, DateTimeOffset OccurredAt) : IEvent;

    [EventName(""test.annotated-only"")]
    public sealed class AnnotatedOnlyClass
    {
    }

    public abstract class AbstractEventClass : IEvent
    {
        public abstract EventId Id { get; }
        public abstract DateTimeOffset OccurredAt { get; }
    }

    public interface IEventSubInterface : IEvent
    {
    }

    public sealed class NonEventClass
    {
    }
}
";

        var compilation = RoslynTestBed.CreateCompilation(sourceCode);
        var runResult = RoslynTestBed.RunGenerator(
            new EventIncrementalGenerator(),
            compilation,
            out var outputCompilation,
            out var diagnostics);

        diagnostics.Should().BeEmpty();
        runResult.GeneratedTrees.Should().HaveCount(1);

        var generatedSource = runResult.GeneratedTrees[0].ToString();

        var expectedSource = @"// <auto-generated />
#nullable enable

namespace EricksonLopez.Events.Generated;

using System;
using System.Collections.Generic;
using EricksonLopez.Events.Identifiers;
using EricksonLopez.Events.Registry;

/// <summary>
/// Compile-time generated event registry containing zero-reflection descriptors.
/// </summary>
public static class GeneratedEventRegistry
{
    /// <summary>
    /// Creates an immutable <see cref=""IEventTypeRegistry""/> with all compile-time discovered event descriptors.
    /// </summary>
    public static IEventTypeRegistry CreateRegistry()
    {
        var descriptors = new List<EventTypeDescriptor>(3);

        descriptors.Add(new EventTypeDescriptor(
            typeof(global::TestApp.AnnotatedOnlyClass),
            new EventType(""test.annotated-only""),
            new EventVersion(1u),
            null));

        descriptors.Add(new EventTypeDescriptor(
            typeof(global::TestApp.PlainDiscoveredEvent),
            new EventType(""PlainDiscoveredEvent""),
            new EventVersion(1u),
            null));

        descriptors.Add(new EventTypeDescriptor(
            typeof(global::TestApp.TestOrderPlaced),
            new EventType(""test.order-placed""),
            new EventVersion(2u),
            ""test-service""));

        return new EventTypeRegistry(descriptors);
    }
}";

        NormalizeCode(generatedSource).Should().Be(NormalizeCode(expectedSource));

        // Runtime compilation and execution check via RoslynTestBed
        var asm = RoslynTestBed.EmitAndLoadAssembly(outputCompilation);
        var regType = asm.GetType("EricksonLopez.Events.Generated.GeneratedEventRegistry");
        regType.Should().NotBeNull();
        var createMethod = regType!.GetMethod("CreateRegistry", BindingFlags.Public | BindingFlags.Static);
        createMethod.Should().NotBeNull();

        var registry = createMethod!.Invoke(null, null) as IEventTypeRegistry;
        registry.Should().NotBeNull();
        registry!.GetAllDescriptors().Count.Should().Be(3);

        var orderType = asm.GetType("TestApp.TestOrderPlaced")!;
        registry.TryGetDescriptor(orderType, out var orderDesc).Should().BeTrue();
        orderDesc!.EventType.Value.Should().Be("test.order-placed");
        orderDesc.Version.Value.Should().Be(2u);
        orderDesc.Source.Should().Be("test-service");

        var annotatedType = asm.GetType("TestApp.AnnotatedOnlyClass")!;
        registry.TryGetDescriptor(annotatedType, out var annDesc).Should().BeTrue();
        annDesc!.EventType.Value.Should().Be("test.annotated-only");
        annDesc.Version.Value.Should().Be(1u);
        annDesc.Source.Should().BeNull();

        var plainType = asm.GetType("TestApp.PlainDiscoveredEvent")!;
        registry.TryGetDescriptor(plainType, out var plainDesc).Should().BeTrue();
        plainDesc!.EventType.Value.Should().Be("PlainDiscoveredEvent");
        plainDesc.Version.Value.Should().Be(1u);
        plainDesc.Source.Should().BeNull();
    }

