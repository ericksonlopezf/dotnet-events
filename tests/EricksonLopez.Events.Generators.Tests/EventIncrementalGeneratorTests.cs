    [Fact]
    public void Generator_WithHandlers_ShouldEmitExactSource_AndExecuteRuntimeDIChaining()
    {
        var sourceCode = @"
using System.Threading.Tasks;

namespace HandlerApp
{
    public sealed record OrderPlaced(EventId Id, DateTimeOffset OccurredAt) : IDomainEvent;

    public sealed class OrderPlacedHandler : IEventHandler<OrderPlaced>
    {
        public ValueTask HandleAsync(OrderPlaced eventInstance, System.Threading.CancellationToken cancellationToken = default) =>
            ValueTask.CompletedTask;
    }
}
";

        var compilation = RoslynTestBed.CreateCompilation(sourceCode, "ExactHandlerCompilation");
        var runResult = RoslynTestBed.RunGenerator(
            new EventIncrementalGenerator(),
            compilation,
            out var outputCompilation,
            out var diagnostics);

        diagnostics.Should().BeEmpty();
        runResult.GeneratedTrees.Should().HaveCount(2);

        var extensionsTree = runResult.GeneratedTrees.FirstOrDefault(t => t.FilePath.Contains("GeneratedEventServiceCollectionExtensions"));
        extensionsTree.Should().NotBeNull();

        var generatedSource = extensionsTree!.ToString();

        var expectedSource = @"// <auto-generated />
#nullable enable

namespace Microsoft.Extensions.DependencyInjection;

using System;
using EricksonLopez.Events.Contracts;
using Microsoft.Extensions.DependencyInjection;

/// <summary>
/// Compile-time generated DI extension methods for discovered event handlers.
/// </summary>
public static class GeneratedEventServiceCollectionExtensions
{
    /// <summary>
    /// Automatically registers all compile-time discovered event handlers in the service collection.
    /// </summary>
    /// <param name=""services"">The service collection.</param>
    /// <param name=""lifetime"">The service lifetime (defaults to Transient).</param>
    /// <returns>The service collection for chaining.</returns>
    public static IServiceCollection AddGeneratedEventHandlers(
        this IServiceCollection services,
        ServiceLifetime lifetime = ServiceLifetime.Transient)
    {
        ArgumentNullException.ThrowIfNull(services);

        services.Add(new ServiceDescriptor(
            typeof(IEventHandler<global::HandlerApp.OrderPlaced>),
            typeof(global::HandlerApp.OrderPlacedHandler),
            lifetime));

        return services;
    }
}
";

        NormalizeCode(generatedSource).Should().Be(NormalizeCode(expectedSource));

        // Runtime check
        var asm = RoslynTestBed.EmitAndLoadAssembly(outputCompilation);
        var extType = asm.GetType("Microsoft.Extensions.DependencyInjection.GeneratedEventServiceCollectionExtensions");
        extType.Should().NotBeNull();
        var addMethod = extType!.GetMethod("AddGeneratedEventHandlers", BindingFlags.Public | BindingFlags.Static);
        addMethod.Should().NotBeNull();

        var services = new ServiceCollection();
        var ret = addMethod!.Invoke(null, new object[] { services, ServiceLifetime.Transient });
        ret.Should().BeSameAs(services);
        services.Should().ContainSingle(sd =>
            sd.ServiceType.Name.StartsWith("IEventHandler") &&
            sd.ImplementationType!.Name == "OrderPlacedHandler" &&
            sd.Lifetime == ServiceLifetime.Transient);
    }

