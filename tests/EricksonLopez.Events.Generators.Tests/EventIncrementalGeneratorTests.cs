        source.Should().Contain("typeof(IEventHandler<global::MultiApp.EventA>)");
        source.Should().Contain("typeof(IEventHandler<global::MultiApp.EventB>)");
        source.Should().Contain("typeof(global::MultiApp.DualHandler)");
