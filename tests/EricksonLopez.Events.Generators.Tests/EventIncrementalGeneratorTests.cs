    [Fact]
    public void Generator_WithMultipleHandlersAndMultipleInterfaces_ShouldEmitAllRegistrations()
    {
        var sourceCode = @"
namespace MultiApp
{
    public sealed record EventA(EventId Id, DateTimeOffset OccurredAt) : IDomainEvent;
    public sealed record EventB(EventId Id, DateTimeOffset OccurredAt) : IDomainEvent;

    public sealed class DualHandler : IEventHandler<EventA>, IEventHandler<EventB>
    {
        public ValueTask HandleAsync(EventA evt, System.Threading.CancellationToken ct = default) => ValueTask.CompletedTask;
        public ValueTask HandleAsync(EventB evt, System.Threading.CancellationToken ct = default) => ValueTask.CompletedTask;
    }

    public abstract class AbstractHandler : IEventHandler<EventA>
    {
        public abstract ValueTask HandleAsync(EventA evt, System.Threading.CancellationToken ct = default);
    }

    public interface IHandlerInterface : IEventHandler<EventA> { }

    public class GenericHandler<T> : IEventHandler<EventA>
